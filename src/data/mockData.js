// Función para crear 2 equipos aleatorios
export const createRandomTeams = (players) => {
  if (!players || players.length === 0) return [];

  // Hacer una copia y mezclar aleatoriamente los jugadores
  const shuffled = [...players].sort(() => Math.random() - 0.5);

  // Dividir en dos grupos
  const midpoint = Math.ceil(shuffled.length / 2);
  const team1Players = shuffled.slice(0, midpoint);
  const team2Players = shuffled.slice(midpoint);

  // Create teams with assigned patterns
  const teams = [
    {
      id: 1,
      name: team1Players.map(p => p.name).join(' & '),
      players: team1Players,
      patternId: 0 // pattern1
    },
    {
      id: 2,
      name: team2Players.map(p => p.name).join(' & '),
      players: team2Players,
      patternId: 1 // pattern2
    }
  ];

  return teams;
};

